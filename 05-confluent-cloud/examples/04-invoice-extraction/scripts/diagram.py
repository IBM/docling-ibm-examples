#!/usr/bin/env python3
"""The pipeline's diagram, generated from the SQL it describes.

    python3 scripts/diagram.py            rewrite the diagram in README.md
    python3 scripts/diagram.py --check    exit 1 if README.md is out of date
    python3 scripts/diagram.py --print    print the Mermaid source only
    python3 scripts/diagram.py --json     print the graph, as the dashboard reads it

A drawn diagram is out of date the first time someone adds a table. This one
is read off ``flink/`` — the same files ``./setup.sh`` and ``./pipeline.sh``
run — so it cannot disagree with them:

* a **table** for every ``CREATE TABLE`` — the inputs the control app
  writes and the outputs the statement writes (*upsert* when keyed);
* a **view** for every ``CREATE VIEW``, with the UDFs it calls and what it
  does (JOIN, GROUP BY, latest per key) — the views are where the work is;
* an **edge** for every relation a view reads, and for every ``INSERT INTO``
  of a long-running statement, from the view it selects from to the table it
  writes (labelled GROUP BY when it aggregates). A read bounded by an OPTIONS
  hint — the history a redeploy rebuilds from — is a *history* edge: drawn
  dashed, and not counted when laying the graph out, since it points back;
* the **statement** (``flink/3*.sql``) as a frame around the views it runs;
* the **control app** writing the input tables, and the **dashboard** reading
  every table only the statement's history reads.

The same graph drives the dashboard's pipeline tab (``--json``, served by the
control app), so the two pictures are one. The UDF tests run ``--check``: a
SQL change that forgets the README fails ``uv run pytest`` rather than a
reader. Standard library only.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
EXAMPLE = HERE.parent
README = EXAMPLE / "README.md"
BEGIN = "<!-- pipeline-diagram:begin — generated by scripts/diagram.py; edit the SQL, not this -->"
END = "<!-- pipeline-diagram:end -->"

_ASSIGN = re.compile(r'^([A-Z_][A-Z0-9_]*)="?([^"\n#]*)"?', re.MULTILINE)
_PLACEHOLDER = re.compile(r"\$\{([A-Za-z_][A-Za-z0-9_]*)\}")
_DEFAULT = re.compile(r"\$\{([A-Za-z_][A-Za-z0-9_]*):-([^}]*)\}")


def names() -> dict[str, str]:
    """env.sh's assignments, with ``${NS}`` left as the literal ``NS``."""
    env: dict[str, str] = {"NS": "NS"}
    for key, value in _ASSIGN.findall((EXAMPLE / "env.sh").read_text(encoding="utf-8")):
        value = _DEFAULT.sub(lambda m: env.get(m.group(1)) or m.group(2), value.strip())  # ${X:-default}
        env[key] = _PLACEHOLDER.sub(lambda m: env.get(m.group(1), m.group(0)), value)
    return env


def short(name: str) -> str:
    """``NS.ex04.spend.daily`` -> ``spend.daily``; ``NS-ex04-pipeline`` -> ``pipeline``."""
    return re.sub(r"^(NS|[a-z0-9]+)[._-]ex04[._-]", "", name)


def _sql(path: Path, env: dict[str, str]) -> str:
    text = _PLACEHOLDER.sub(lambda m: env.get(m.group(1), m.group(0)), path.read_text(encoding="utf-8"))
    # Comments out, string literals blanked: neither may contribute an identifier.
    text = "\n".join(line.split("--", 1)[0] for line in text.splitlines())
    return re.sub(r"'(?:[^']|'')*'", "''", text)


def _reads(sql: str) -> list[str]:
    out: list[str] = []
    for m in re.finditer(r"\b(?:FROM|JOIN)\s+`([^`]+)`", sql):
        if m.group(1) not in out:
            out.append(m.group(1))
    return out


def _ops(sql: str) -> list[str]:
    return [op for op, pat in (("JOIN", r"\bJOIN\b"), ("GROUP BY", r"\bGROUP BY\b"),
                               ("latest per invoice", r"\bROW_NUMBER\s*\(\s*\)\s*OVER\s*\(\s*PARTITION BY\s+`doc_id`"),
                               ("UNION ALL", r"\bUNION ALL\b"))
            if re.search(pat, sql)]


def _hint(raw: str, table: str) -> str:
    """The OPTIONS hint ``table`` is read with in this (raw) SQL, or ''."""
    m = re.search(rf"`{re.escape(table)}`\s*/\*\+\s*OPTIONS\((.*?)\)\s*\*/", raw, re.DOTALL)
    return m.group(1) if m else ""


def build(env: dict[str, str] | None = None) -> dict:
    """``{"nodes": [...], "edges": [[from, to, {meta}], ...]}`` — the pipeline as data.

    ``env`` resolves the names; the default leaves ``NS`` as a placeholder,
    which is what the README wants. The dashboard passes the real one. An
    edge's meta may carry ``label`` and ``style`` (``"history"``).
    """
    env = env or names()
    files = sorted((EXAMPLE / "flink").glob("*.sql"))
    raw = {path: _PLACEHOLDER.sub(lambda m: env.get(m.group(1), m.group(0)), path.read_text(encoding="utf-8"))
           for path in files}
    sql = {path: _sql(path, env) for path in files}
    nodes: dict[str, dict] = {}
    udfs: list[str] = []
    for path, text in sql.items():
        if path.name.startswith("10_function_"):
            udfs.append(re.search(r"FUNCTION\s+`([^`]+)`", text).group(1))

    def calls(text: str) -> list[str]:
        return [u for u in udfs if re.search(rf"\b{re.escape(u)}\s*\(", text)]

    tables: list[str] = []
    views: dict[str, tuple[str, str]] = {}  # name -> (body, raw)
    for path, text in sql.items():
        if path.name.startswith("00_table_"):
            name = re.search(r"TABLE IF NOT EXISTS\s+`([^`]+)`", text).group(1)
            tables.append(name)
            nodes[name] = {"id": name, "kind": "table", "label": short(name), "file": path.name,
                           "flags": ["upsert"] if "PRIMARY KEY" in text else []}
        elif re.match(r"2\d_view_", path.name):
            m = re.search(r"CREATE VIEW\s+`([^`]+)`\s+AS(.*)", text, re.DOTALL)
            views[m.group(1)] = (m.group(2), raw[path])
            nodes[m.group(1)] = {"id": m.group(1), "kind": "view", "label": short(m.group(1)), "file": path.name,
                                 "flags": [], "ops": _ops(m.group(2)), "udfs": calls(m.group(2))}

    edges: list[list] = []
    for name, (body, raw_body) in views.items():
        for src in _reads(body):
            if src in nodes and src != name:
                hint = _hint(raw_body, src)
                if "scan.bounded" in hint:
                    meta = {"style": "history", "label": "history, bounded"}
                elif "scan.startup" in hint:
                    meta = {"label": "new only"}
                else:
                    meta = {}
                edges.append([src, name, meta])

    app = env.get("APP_NAME", "NS-ex04")
    for path, text in sql.items():
        if not re.match(r"3\d_", path.name):
            continue
        stmt = f"{app}-" + re.sub(r"^\d+_", "", path.stem).replace("_", "-")
        members: list[str] = []
        for insert in re.split(r";", text):
            m = re.search(r"INSERT INTO\s+`([^`]+)`", insert)
            if not m or m.group(1) not in nodes:
                continue
            ops = [op for op in _ops(insert) if op == "GROUP BY"]
            for src in _reads(insert):
                if src in views:
                    edges.append([src, m.group(1), {"label": " · ".join(ops)} if ops else {}])
                    members.append(src)
        # The frame: the views its INSERTs read, and the views those read.
        todo = list(members)
        while todo:
            for src in _reads(views[todo.pop()][0]):
                if src in views and src not in members:
                    members.append(src)
                    todo.append(src)
        full = text + "\n".join(views[v][0] for v in members)
        nodes[stmt] = {"id": stmt, "kind": "stmt", "label": short(stmt), "file": path.name, "flags": [],
                       "members": [v for v in views if v in members], "ops": _ops(full), "udfs": calls(full)}

    layout = [e for e in edges if e[2].get("style") != "history"]
    written = {b for _, b, _ in layout}
    read = {a for a, _, _ in layout}
    nodes["control"] = {"id": "control", "kind": "app", "label": "control app", "file": "scripts/control.py",
                        "flags": ["simulated clock"]}
    nodes["dashboard"] = {"id": "dashboard", "kind": "app", "label": "dashboard", "file": "scripts/dashboard.py",
                          "flags": ["Kafka consumer"]}
    inputs = [["control", t, {}] for t in tables if t not in written]
    leaves = [[t, "dashboard", {}] for t in tables if t in written and t not in read]
    order = (["control"] + tables + list(views) + [n for n in nodes if nodes[n]["kind"] == "stmt"] + ["dashboard"])
    return {"nodes": [nodes[n] for n in order], "edges": inputs + edges + leaves}


def mermaid(graph: dict) -> str:
    ids = {n["id"]: re.sub(r"\W", "_", n["label"]) for n in graph["nodes"]}
    lines = ["flowchart LR"]

    def node(n: dict) -> str:
        nid, label = ids[n["id"]], n["label"]
        if n["kind"] == "app":
            return f'{nid}[/"{label}<br/><small>{" · ".join(n["flags"])}</small>"/]:::ext'
        if n["kind"] == "table":
            return f'{nid}(["{label}<br/><small>{" · ".join(["table"] + n["flags"])}</small>"]):::topic'
        what = n["ops"] + [f"{short(u)}()" for u in n["udfs"]]
        return f'{nid}[["{label}<br/><small>{" · ".join(what) or "view"}</small>"]]:::view'

    framed = {v for n in graph["nodes"] if n["kind"] == "stmt" for v in n["members"]}
    for n in graph["nodes"]:
        if n["kind"] in ("app", "table") or (n["kind"] == "view" and n["id"] not in framed):
            lines.append("  " + node(n))
    for n in graph["nodes"]:
        if n["kind"] == "stmt":
            lines.append(f'  subgraph {ids[n["id"]]}["statement · {n["label"]} · flink/{n["file"]}"]')
            for v in n["members"]:
                lines.append("    " + node(next(x for x in graph["nodes"] if x["id"] == v)))
            lines.append("  end")
    for src, dst, meta in graph["edges"]:
        label = meta.get("label")
        if meta.get("style") == "history":
            lines.append(f'  {ids[src]} -. "{label}" .-> {ids[dst]}')
        elif "dashboard" in (src, dst):
            lines.append(f"  {ids[src]} -.-> {ids[dst]}")
        elif label:
            lines.append(f'  {ids[src]} -- "{label}" --> {ids[dst]}')
        else:
            lines.append(f"  {ids[src]} --> {ids[dst]}")
    lines += [
        "  classDef topic fill:#e8f1fc,stroke:#2a78d6,color:#0b0b0b",
        "  classDef view fill:#fff4e5,stroke:#eb6834,color:#0b0b0b",
        "  classDef ext fill:#ffffff,stroke:#898781,color:#52514e,stroke-dasharray: 4 3",
    ]
    return "\n".join(lines)


def block(graph: dict) -> str:
    return f"{BEGIN}\n\n```mermaid\n{mermaid(graph)}\n```\n\n{END}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="exit 1 if README.md is out of date")
    mode.add_argument("--print", action="store_true", help="print the Mermaid source")
    mode.add_argument("--json", action="store_true", help="print the graph as JSON")
    args = parser.parse_args()

    graph = build()
    if args.print:
        print(mermaid(graph))
        return 0
    if args.json:
        print(json.dumps(graph, indent=2))
        return 0
    fresh = block(graph)
    text = README.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        print(f"{README.name}: the markers are missing — add\n\n{BEGIN}\n{END}\n\nwhere the diagram goes", file=sys.stderr)
        return 1
    start, end = text.index(BEGIN), text.index(END) + len(END)
    if text[start:end] == fresh:
        print("README.md: pipeline diagram is up to date")
        return 0
    if args.check:
        print("README.md: the pipeline diagram is out of date — run python3 scripts/diagram.py", file=sys.stderr)
        return 1
    README.write_text(text[:start] + fresh + text[end:], encoding="utf-8")
    print("README.md: pipeline diagram rewritten")
    return 0


if __name__ == "__main__":
    sys.exit(main())
