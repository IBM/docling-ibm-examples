"""data/manifest.jsonl -> src/invoice_udf/_truth.py, for the fake extraction.

A Python module rather than a data file next to the code, because a module is
the one thing the UDF runtime is guaranteed to be able to load: the filesystem
is read-only and package-data handling is one more thing to get wrong in an
sdist. ~170 invoices make a ~200 kB module, far under the artifact limit.

Only ``truth`` goes in, plus the page count and the fake's instructions. The
submission fields stay out — the UDF is given those by the stream, as it would
be in production.
"""

from __future__ import annotations

import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
MANIFEST = HERE.parent / "data" / "manifest.jsonl"
OUT = HERE / "src" / "invoice_udf" / "_truth.py"


def main() -> None:
    if not MANIFEST.exists():
        sys.exit(f"{MANIFEST} not found — run scripts/generate.py first")
    documents = {}
    for line in MANIFEST.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        record = json.loads(line)
        doc = dict(record["truth"])
        doc["pages"] = record.get("pages", 1)
        doc["layout"] = record.get("layout", "")
        doc["missing"] = (record.get("fake_extraction") or {}).get("missing", [])
        documents[record["doc_id"]] = doc
    payload = json.dumps(documents, ensure_ascii=False, sort_keys=True)
    OUT.write_text(
        '"""Generated by compile_truth.py from data/manifest.jsonl. Do not edit."""\n\n'
        "import json\n\n"
        f"DOCUMENTS = json.loads({payload!r})\n",
        encoding="utf-8",
    )
    print(f"{OUT.relative_to(HERE)}: {len(documents)} documents", file=sys.stderr)


if __name__ == "__main__":
    main()
